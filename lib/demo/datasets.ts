function buildDemo(
  id: string,
  name: string,
  filename: string,
  uploadedAt: string,
  analyzedAt: string,
  lines: ReturnType<typeof line>[],
  blurb: string,
): DemoBom {
  return {
    summary: summaryFrom(id, name, filename, uploadedAt, lines),
    analyze: analyze(filename, lines, analyzedAt),
    blurb,
  }
}

